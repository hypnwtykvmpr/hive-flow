// Gate 7 + 8: POSIX signal-trapping child runtime regression
// ---------------------------------------------------------------------------
// Verifies the wrapper exits promptly and emits session-end even when the
// real CLI traps TERM/INT and blocks in its own `wait`.
//
// Gate 8: process-liveness is verified via process.kill(pid, 0), NOT pgrep.
// The fake real CLI writes both its own PID and its inner child PID to files
// so we can assert both are dead after the wrapper exits.

const POSIX_ONLY = platform() === 'darwin' || platform() === 'linux';

function pidIsAlive(pid: number): boolean {
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

async function waitForPidFiles(...paths: string[]): Promise<void> {
  const deadline = Date.now() + 5000;
  while (Date.now() < deadline) {
    if (paths.every((p) => existsSync(p))) return;
    await new Promise((r) => setTimeout(r, 50));
  }
  throw new Error('PID files not created within 5s: ' + paths.filter((p) => !existsSync(p)).join(', '));
}

