// cli/src/integrations/__tests__/wrapper-driver.test.ts
//
// Wave 11 wrapper-driver tests. Covers:
//   - POSIX template structure (no `set -e`, trap on EXIT/INT/TERM, validated
//     heartbeat regex, shell-quoted paths).
//   - Windows .cmd template structure (Node-based dispatch, CRLF endings,
//     CMD %ERRORLEVEL% propagation).
//   - `writeWrapper` symlink-safe parent creation (Wave 8.4
//     `ensureSafeUserCacheDir` integration).
//   - Permission semantics (0o755 on POSIX, irrelevant on Windows).
//   - Shell-quote round-trip for adversarial paths (spaces, apostrophes,
//     command-injection attempts via `;`).
//   - HostCli validation.
//   - HIVE_FLOW_HEARTBEAT_SECONDS validation (Wave 7.5 round-5 fork-bomb
//     hardening). NaN, zero, negative -> default; only positive integers
//     pass.

import { afterAll, beforeEach, describe, expect, it } from 'vitest';
import { mkdtemp, mkdir, readFile, stat, symlink, lstat, chmod, writeFile } from 'node:fs/promises';
