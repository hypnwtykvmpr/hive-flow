// ---------------------------------------------------------------------------
// Static source audit. The previous wrapper-driver.ts used an unsafe
// `value as HostCli` cast inside `Set.has`. Wave 11 widens the set to
// `ReadonlySet<string>` so the cast is no longer needed. This test reads
// the source file directly and asserts the legacy cast is gone.
// ---------------------------------------------------------------------------

function stripCommentsAndStrings(ts: string): string {
  // Crude but sufficient for source audit: strip `//` line comments and
  // `/* ... */` block comments so docstring mentions of a banned cast pattern
  // do not produce false positives. We also strip single- and double-quoted
  // string literals because they may contain the cast verbatim inside test
  // fixtures or error messages.
  let out = ts.replace(/\/\*[\s\S]*?\*\//g, '');
  out = out.replace(/(^|\n)\s*\/\/[^\n]*/g, '$1');
  out = out.replace(/"(?:[^"\\\n]|\\.)*"/g, '""');
  out = out.replace(/'(?:[^'\\\n]|\\.)*'/g, "''");
  // template literals: drop the entire content between backticks. JS regex
  // does not support recursive matching so we use a non-greedy match — this
  // is best-effort and acceptable because we don't render code inside
  // template literals in this source file.
  out = out.replace(/`(?:[^`\\]|\\.)*`/g, '``');
  return out;
}

