describe('renderWindowsWrapper', () => {
  const baseOpts = {
    realCliBin: 'C:\\Program Files\\Codex\\codex.exe',
    hostCli: 'codex' as const,
    hiveFlowCli: 'C:\\Users\\dev\\hive-flow\\bin\\cli.js',
  };

  it('starts with @ECHO OFF and includes AUTO-GENERATED marker', () => {
    const script = renderWindowsWrapper(baseOpts);
    expect(script.startsWith('@ECHO OFF')).toBe(true);
    expect(script).toContain('AUTO-GENERATED by hive-flow wrapper-driver');
  });

  it('uses CRLF line endings', () => {
    const script = renderWindowsWrapper(baseOpts);
    expect(script).toContain('\r\n');
    // No bare LF lines.
    const lines = script.split('\r\n');
    for (const line of lines) {
      expect(line).not.toContain('\n');
    }
  });

  it('dispatches via Node-based wrapper-host subcommand', () => {
    const script = renderWindowsWrapper(baseOpts);
    expect(script).toContain('node ');
    expect(script).toContain('statusline wrapper-host');
  });

  it('passes hostCli, hiveFlowCli, and realCliBin in correct order', () => {
    const script = renderWindowsWrapper(baseOpts);
    // The actual content uses single backslashes (Windows path separator);
    // the regex needs single `\\` to match one backslash literal.
    expect(script).toMatch(
      /node "C:\\Users\\dev\\hive-flow\\bin\\cli\.js" statusline wrapper-host "codex" --heartbeat-default \d+ -- "C:\\Program Files\\Codex\\codex\.exe" %\*/,
    );
  });

  it('sets client kind and optional project root before wrapper-host dispatch', () => {
    const script = renderWindowsWrapper({
      ...baseOpts,
      projectRoot: 'C:\\Users\\test\\project-one',
    });
    expect(script).toContain('SET "HIVE_FLOW_CLIENT_KIND=codex"');
    expect(script).toContain('SET "HIVE_FLOW_PROJECT_ROOT=C:\\Users\\test\\project-one"');
  });

  it('omits explicit project root from user-scoped Windows wrappers', () => {
    const script = renderWindowsWrapper(baseOpts);
    expect(script).not.toContain('HIVE_FLOW_PROJECT_ROOT=');
  });

  it('quotes paths with spaces using CMD double-quote convention', () => {
    const script = renderWindowsWrapper({
      ...baseOpts,
      realCliBin: 'C:\\Program Files\\Codex\\codex.exe',
    });
    expect(script).toContain('"C:\\Program Files\\Codex\\codex.exe"');
  });

  it('captures and propagates %ERRORLEVEL%', () => {
    const script = renderWindowsWrapper(baseOpts);
    expect(script).toContain('SET EXITCODE=%ERRORLEVEL%');
    expect(script).toContain('EXIT /B %EXITCODE%');
  });

  it('uses SETLOCAL/ENDLOCAL to isolate env mutations', () => {
    const script = renderWindowsWrapper(baseOpts);
    expect(script).toContain('SETLOCAL');
    expect(script).toContain('ENDLOCAL');
  });

  it('rejects realCliBin containing % (CMD variable expansion)', () => {
    expect(() =>
      renderWindowsWrapper({
        ...baseOpts,
        realCliBin: 'C:\\foo\\%PATH%\\cli.exe',
      }),
    ).toThrow(/%/);
  });

  it('rejects hiveFlowCli containing % (CMD variable expansion)', () => {
    expect(() =>
      renderWindowsWrapper({
        ...baseOpts,
        hiveFlowCli: 'C:\\foo\\%PATH%\\cli.js',
      }),
    ).toThrow(/%/);
  });

  it('rejects control characters (NaN-bypass: cannot smuggle newlines into the CMD)', () => {
    expect(() =>
      renderWindowsWrapper({
        ...baseOpts,
        realCliBin: 'C:\\foo' + String.fromCharCode(0) + '\\cli.exe',
      }),
    ).toThrow(/control characters/i);
  });

  it('renders heartbeat default flag (Number.isFinite + >= 1 validated downstream)', () => {
    const script = renderWindowsWrapper(baseOpts);
    expect(script).toContain('--heartbeat-default 5');
  });

  it('honors HIVE_FLOW_HEARTBEAT_SECONDS env override at render time', () => {
    const script = renderWindowsWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_HEARTBEAT_SECONDS: '12' },
    });
    expect(script).toContain('--heartbeat-default 12');
  });

  it('rejects invalid HIVE_FLOW_HEARTBEAT_SECONDS at render time (NaN -> 5)', () => {
    const script = renderWindowsWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_HEARTBEAT_SECONDS: 'NaN' },
    });
    expect(script).toContain('--heartbeat-default 5');
  });

  it('rejects zero / negative HIVE_FLOW_HEARTBEAT_SECONDS (Wave 7.5 fork-bomb hardening)', () => {
    const zero = renderWindowsWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_HEARTBEAT_SECONDS: '0' },
    });
    expect(zero).toContain('--heartbeat-default 5');
    const neg = renderWindowsWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_HEARTBEAT_SECONDS: '-3' },
    });
    expect(neg).toContain('--heartbeat-default 5');
  });

  it('rejects invalid hostCli', () => {
    expect(() =>
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      renderWindowsWrapper({ ...baseOpts, hostCli: 'unknown-cli' as any }),
    ).toThrow(/HostCli/);
  });
});

