// ---------------------------------------------------------------------------
// renderPosixWrapper
// ---------------------------------------------------------------------------

describe('renderPosixWrapper', () => {
  const baseOpts = {
    realCliBin: '/opt/codex/bin/codex',
    hostCli: 'codex' as const,
    hiveFlowCli: '/usr/local/bin/hive-flow',
  };

  it('contains shebang and AUTO-GENERATED marker', () => {
    const script = renderPosixWrapper(baseOpts);
    expect(script.startsWith('#!/usr/bin/env bash\n')).toBe(true);
    expect(script).toContain('AUTO-GENERATED by hive-flow wrapper-driver');
  });

  it('contains realCliBin, hiveFlowCli, and hostCli', () => {
    const script = renderPosixWrapper(baseOpts);
    expect(script).toContain("HIVE_FLOW_REAL_CLI='/opt/codex/bin/codex'");
    expect(script).toContain("HIVE_FLOW_BIN='/usr/local/bin/hive-flow'");
    expect(script).toContain("HIVE_FLOW_HOSTCLI='codex'");
  });

  it('exports client kind for shared-core MCP/statusline routing', () => {
    const script = renderPosixWrapper(baseOpts);
    expect(script).toContain("HIVE_FLOW_CLIENT_KIND='codex'");
    expect(script).toContain('export HIVE_FLOW_CLIENT_KIND');
  });

  it('exports explicit project root when rendered for a project-scoped wrapper', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      projectRoot: '/Users/test/work/project-one',
    });
    expect(script).toContain("HIVE_FLOW_PROJECT_ROOT='/Users/test/work/project-one'");
    expect(script).toContain('export HIVE_FLOW_PROJECT_ROOT');
  });

  it('omits explicit project root when rendered for a user-scoped wrapper', () => {
    const script = renderPosixWrapper(baseOpts);
    expect(script).not.toContain('HIVE_FLOW_PROJECT_ROOT=');
  });

  it('uses `set -uo pipefail` and NOT `set -e`', () => {
    const script = renderPosixWrapper(baseOpts);
    expect(script).toContain('set -uo pipefail');
    // `set -e` standalone on its own line would abort on session-event
    // emission failures. Allow `set -uo pipefail` (which doesn't contain
    // ` -e ` as a standalone option).
    const lines = script.split('\n');
    for (const line of lines) {
      const trimmed = line.trim();
      // Reject any line that sets the `errexit` shell option in any form.
      expect(trimmed).not.toBe('set -e');
      expect(trimmed).not.toBe('set -e ');
      expect(trimmed).not.toMatch(/^set\s+-[a-z]*e[a-z]*$/);
    }
  });

  it('traps INT and TERM (signal-induced session-end)', () => {
    const script = renderPosixWrapper(baseOpts);
    // Wave 11 fix: the wrapper no longer relies on an EXIT trap because the
    // real CLI runs as a child (not via `exec`). Normal-exit session-end is
    // emitted explicitly after the child returns; signal-induced exits go
    // through the INT/TERM traps which exit with 128+signal.
    expect(script).toContain('trap hf_on_int INT');
    expect(script).toContain('trap hf_on_term TERM');
    expect(script).toContain('hf_on_int() {');
    expect(script).toContain('hf_on_term() {');
    expect(script).toContain('hf_emit_session_end() {');
  });

  it('emits session-start, session-heartbeat, session-end events', () => {
    const script = renderPosixWrapper(baseOpts);
    expect(script).toContain(
      'statusline session-start --host-cli "$HIVE_FLOW_HOSTCLI" --pid "$HIVE_FLOW_PID"',
    );
    expect(script).toContain(
      'statusline session-heartbeat --host-cli "$HIVE_FLOW_HOSTCLI" --pid "$HIVE_FLOW_PID"',
    );
    // session-end is now emitted via hf_emit_session_end which takes a code
    // parameter. The bound variable name in the helper is `$code`.
    expect(script).toContain(
      'statusline session-end --host-cli "$HIVE_FLOW_HOSTCLI" --pid "$HIVE_FLOW_PID" --exit-code "$code"',
    );
  });

  it('all session-event calls are best-effort (|| true with stderr suppressed)', () => {
    const script = renderPosixWrapper(baseOpts);
    // Every session-event call must end with `2>/dev/null || true` so a
    // missing or crashing hive-flow CLI cannot abort the wrapper.
    const sessionEventLines = script
      .split('\n')
      .filter((l) => l.includes('statusline session-'));
    expect(sessionEventLines.length).toBeGreaterThanOrEqual(3);
    for (const line of sessionEventLines) {
      expect(line).toContain('2>/dev/null');
      expect(line).toContain('|| true');
    }
  });

  it('validates heartbeat env via a positive-integer regex', () => {
    const script = renderPosixWrapper(baseOpts);
    // Anti-fork-bomb: only `^[1-9][0-9]*$` is accepted. `0`, negatives, and
    // non-numeric strings collapse to the default. We assert the literal
    // regex appears in the rendered script.
    expect(script).toContain("grep -E '^[1-9][0-9]*$'");
  });

  it('rendered default heartbeat is 5 seconds', () => {
    const script = renderPosixWrapper(baseOpts);
    // Default fallback used in both the bash assignment AND the post-pipe
    // `|| echo 5` should match the rendered constant.
    expect(script).toMatch(/HIVE_FLOW_HEARTBEAT_SECONDS:-5/);
    expect(script).toMatch(/\|\| echo 5/);
  });

  it('honors HIVE_FLOW_HEARTBEAT_SECONDS env override at render time', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_HEARTBEAT_SECONDS: '10' },
    });
    expect(script).toMatch(/HIVE_FLOW_HEARTBEAT_SECONDS:-10/);
    expect(script).toMatch(/\|\| echo 10/);
  });

  it('rejects invalid HIVE_FLOW_HEARTBEAT_SECONDS at render time (NaN -> 5)', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_HEARTBEAT_SECONDS: 'NaN' },
    });
    expect(script).toMatch(/HIVE_FLOW_HEARTBEAT_SECONDS:-5/);
  });

  it('rejects zero HIVE_FLOW_HEARTBEAT_SECONDS at render time (0 -> 5)', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_HEARTBEAT_SECONDS: '0' },
    });
    expect(script).toMatch(/HIVE_FLOW_HEARTBEAT_SECONDS:-5/);
  });

  it('rejects negative HIVE_FLOW_HEARTBEAT_SECONDS at render time (-1 -> 5)', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_HEARTBEAT_SECONDS: '-1' },
    });
    expect(script).toMatch(/HIVE_FLOW_HEARTBEAT_SECONDS:-5/);
  });

  it('rendered default kill-grace is 1 second', () => {
    const script = renderPosixWrapper(baseOpts);
    expect(script).toMatch(/HIVE_FLOW_KILL_GRACE_SECONDS:-1/);
    expect(script).toMatch(/\|\| echo 1\b/);
  });

  it('honors HIVE_FLOW_KILL_GRACE_SECONDS env override at render time', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_KILL_GRACE_SECONDS: '3' },
    });
    expect(script).toMatch(/HIVE_FLOW_KILL_GRACE_SECONDS:-3/);
    expect(script).toMatch(/\|\| echo 3\b/);
  });

  it('rejects invalid HIVE_FLOW_KILL_GRACE_SECONDS at render time (NaN -> 1)', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      env: { HIVE_FLOW_KILL_GRACE_SECONDS: 'bad' },
    });
    expect(script).toMatch(/HIVE_FLOW_KILL_GRACE_SECONDS:-1/);
  });

  it('renders bounded-grace kill pattern in POSIX script (Wave 11A.7 audit)', () => {
    const script = renderPosixWrapper(baseOpts);
    const sourceOnly = script
      .split('\n')
      .filter((line) => !line.trimStart().startsWith('#'))
      .join('\n');
    expect(sourceOnly).toContain('kill -KILL "$HIVE_FLOW_CHILD_PID"');
    expect(sourceOnly).toContain('kill -0 "$HIVE_FLOW_CHILD_PID"');
    expect(sourceOnly).toContain('HIVE_FLOW_KILL_GRACE_SECONDS');
    expect(sourceOnly).toContain('sleep 0.2');
  });

  it('runs the real CLI as a BACKGROUND child and waits (Wave 11A.6)', () => {
    const script = renderPosixWrapper(baseOpts);
    // Wave 11A.6: the real CLI is launched in the background so INT/TERM
    // traps fire promptly. We assert the `&` backgrounding form and the
    // subsequent `wait` on the child PID. Strip comments before matching
    // so docstring references do not produce false positives.
    const sourceOnly = script
      .split('\n')
      .filter((line) => !line.trimStart().startsWith('#'))
      .join('\n');
    expect(sourceOnly).toContain('"$HIVE_FLOW_REAL_CLI" "$@" &');
    expect(sourceOnly).toContain('HIVE_FLOW_CHILD_PID=$!');
    expect(sourceOnly).toContain('wait "$HIVE_FLOW_CHILD_PID"');
    expect(script).toContain('HIVE_FLOW_EXIT=$?');
    expect(script).toContain('exit "$HIVE_FLOW_EXIT"');
  });

  it('does NOT use `exec` to launch the real CLI (regression guard)', () => {
    // Bug pattern from the Wave 11 audit: any line that uses `exec` to
    // invoke the real CLI binary replaces the wrapper shell and prevents
    // the trap-driven session-end from ever firing. We grep the rendered
    // script for that exact pattern and assert zero hits.
    const script = renderPosixWrapper(baseOpts);
    const execHits = script
      .split('\n')
      .filter((line) => {
        const trimmed = line.trimStart();
        // Comments and docstrings are fine; only real source lines matter.
        if (trimmed.startsWith('#')) return false;
        return /\bexec\s+"\$HIVE_FLOW_REAL_CLI"/.test(trimmed);
      });
    expect(execHits).toEqual([]);
  });

  it('emits session-end exactly once (idempotent via HIVE_FLOW_END_EMITTED)', () => {
    const script = renderPosixWrapper(baseOpts);
    // The shared cleanup helper short-circuits if session-end was already
    // emitted, so the INT/TERM trap path and the normal path cannot
    // double-emit when both run (e.g., trap re-fires during shutdown).
    expect(script).toContain('HIVE_FLOW_END_EMITTED=0');
    expect(script).toContain('HIVE_FLOW_END_EMITTED=1');
    expect(script).toContain(
      'if [ "$HIVE_FLOW_END_EMITTED" = "0" ]; then',
    );
  });

  it('starts a background heartbeat loop guarded by `kill -0`', () => {
    const script = renderPosixWrapper(baseOpts);
    expect(script).toContain('while kill -0 "$HIVE_FLOW_PID" 2>/dev/null; do');
    // The loop must run in a backgrounded subshell.
    expect(script).toMatch(/\) &/);
    expect(script).toContain('HIVE_FLOW_HB_PID=$!');
  });

  it('shell-quotes paths with spaces correctly', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      realCliBin: '/opt/foo bar/cli',
    });
    expect(script).toContain("HIVE_FLOW_REAL_CLI='/opt/foo bar/cli'");
  });

  it('shell-quotes paths with apostrophes correctly (close/escape/reopen)', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      realCliBin: "/opt/foo's tool/cli",
    });
    // `'/opt/foo'\''s tool/cli'` is the canonical bash-safe encoding.
    expect(script).toContain(
      "HIVE_FLOW_REAL_CLI='/opt/foo'\\''s tool/cli'",
    );
  });

  it('shell-quotes adversarial paths (command-injection attempt is neutralised)', () => {
    const script = renderPosixWrapper({
      ...baseOpts,
      realCliBin: '/opt/x; rm -rf /',
    });
    // The `;` and `rm` must be inside single quotes — never as bare tokens.
    expect(script).toContain("HIVE_FLOW_REAL_CLI='/opt/x; rm -rf /'");
    // Explicit anti-regression: no occurrence of unquoted `rm -rf /`.
    expect(script).not.toMatch(/^\s*rm\s+-rf\s+\//m);
  });

  it('rejects realCliBin containing control bytes (NUL)', () => {
    expect(() =>
      renderPosixWrapper({
        ...baseOpts,
        realCliBin: '/opt/x' + String.fromCharCode(0) + '/cli',
      }),
    ).toThrow(/control characters/i);
  });

  it('rejects realCliBin containing control bytes (LF)', () => {
    expect(() =>
      renderPosixWrapper({
        ...baseOpts,
        realCliBin: '/opt/x\n/cli',
      }),
    ).toThrow(/control characters/i);
  });

  it('rejects realCliBin containing control bytes (CR)', () => {
    expect(() =>
      renderPosixWrapper({
        ...baseOpts,
        realCliBin: '/opt/x\r/cli',
      }),
    ).toThrow(/control characters/i);
  });

  it('rejects relative realCliBin', () => {
    expect(() =>
      renderPosixWrapper({
        ...baseOpts,
        realCliBin: 'codex',
      }),
    ).toThrow(/absolute POSIX path/i);
  });

  it('rejects empty realCliBin', () => {
    expect(() =>
      renderPosixWrapper({
        ...baseOpts,
        realCliBin: '',
      }),
    ).toThrow(/non-empty/i);
  });

  it('rejects relative hiveFlowCli', () => {
    expect(() =>
      renderPosixWrapper({
        ...baseOpts,
        hiveFlowCli: 'hive-flow',
      }),
    ).toThrow(/absolute POSIX path/i);
  });

  it('rejects invalid hostCli', () => {
    expect(() =>
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      renderPosixWrapper({ ...baseOpts, hostCli: 'not-a-real-cli' as any }),
    ).toThrow(/HostCli/);
  });

  it('accepts every valid HostCli union member', () => {
    const valid = [
      'claude-code',
      'codex',
      'gemini',
      'forgecode',
      'cursor-cli',
      'qwen',
      'opencode',
      'hive-flow-daemon',
      'wrapper',
    ] as const;
    for (const h of valid) {
      expect(() =>
        renderPosixWrapper({ ...baseOpts, hostCli: h }),
      ).not.toThrow();
    }
  });
});

